#!/bin/bash

# ===== ГЕНЕРАТОР ПАРОЛЕЙ =====
# Этот скрипт создает случайные пароли заданной длины
# Использование: ./genpass.sh [длина] [опции]
# Примеры:
#   ./genpass.sh        — пароль из 16 символов
#   ./genpass.sh 24     — пароль из 24 символов
#   ./genpass.sh 32 -s  — пароль из 32 символов со спецсимволами

# ===== НАСТРОЙКИ ПО УМОЛЧАНИЮ =====
# Если пользователь не указал длину, используем 16
LENGTH=${1:-16}

# Проверяем, что длина — это число
# !~ — оператор "не соответствует регулярному выражению"
# ^[0-9]+$ — означает "только цифры от начала до конца строки"
if ! [[ "$LENGTH" =~ ^[0-9]+$ ]]; then
    echo "Ошибка: длина должна быть числом!"
    echo "Использование: $0 [длина]"
    exit 1
fi

# Проверяем, указан ли флаг -s (спецсимволы)
# $2 — второй аргумент командной строки
USE_SPECIAL=false
if [ "$2" == "-s" ]; then
    USE_SPECIAL=true
fi

# ===== ГЕНЕРАЦИЯ ПАРОЛЯ =====

# Определяем набор символов
# tr -dc — удалить всё, кроме указанных символов (delete complement)
# /dev/urandom — специальный файл Linux, который выдает случайные байты
if [ "$USE_SPECIAL" = true ]; then
    # Со спецсимволами: буквы, цифры, !@#$%^&*
    CHARSET='A-Za-z0-9!@#$%^&*'
else
    # Без спецсимволов: только буквы и цифры
    CHARSET='A-Za-z0-9'
fi

# Генерируем пароль
# 1. cat /dev/urandom — читаем случайные байты
# 2. tr -dc "$CHARSET" — оставляем только нужные символы
# 3. head -c $LENGTH — берем первые $LENGTH символов
# 4. Сохраняем в переменную PASSWORD
PASSWORD=$(cat /dev/urandom | tr -dc "$CHARSET" | head -c $LENGTH)

# ===== ВЫВОД РЕЗУЛЬТАТА =====

echo "Сгенерированный пароль:"
echo "$PASSWORD"
echo ""
echo "Длина: $LENGTH символов"
echo "Спецсимволы: $USE_SPECIAL"
